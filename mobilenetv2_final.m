clearvars -except imdsTrain imdsVal imdsTest;
gpuDevice([]); 

if ~exist("imdsTrain", "var")
    load("food11_datastores.mat");
end 

inputSize = [224 224 3]; 
numClasses = 11;

augmenter = imageDataAugmenter( ...
    RandXReflection=true, ...          
    RandRotation=[-15 15], ...         
    RandScale=[0.9 1.1], ...           
    RandXTranslation=[-15 15], ...     
    RandYTranslation=[-15 15]);        

augTrain = augmentedImageDatastore(inputSize(1:2), imdsTrain, DataAugmentation=augmenter);
augVal   = augmentedImageDatastore(inputSize(1:2), imdsVal);

netPretrained = mobilenetv2;
lgraph = layerGraph(netPretrained);

newFCLayer = fullyConnectedLayer(numClasses, ...
    Name="new_fc", ...
    WeightLearnRateFactor=10, ... 
    BiasLearnRateFactor=10);

lgraph = replaceLayer(lgraph, "Logits", newFCLayer);
lgraph = removeLayers(lgraph, "ClassificationLayer_Logits");

batchSize = 64;
iterationsPerEpoch = floor(numel(imdsTrain.Files) / batchSize); 

options = trainingOptions("sgdm", ...
    InitialLearnRate=5e-4, ...
    Momentum=0.9, ...
    LearnRateSchedule="piecewise", ...          
    LearnRateDropPeriod=7, ...                  
    LearnRateDropFactor=0.2, ...                
    L2Regularization=2e-4, ...                  % L2 allégée
    ExecutionEnvironment="gpu", ...
    MaxEpochs=18, ...
    Shuffle="every-epoch", ...
    MiniBatchSize=batchSize, ...
    ValidationData=augVal, ...
    ValidationFrequency=iterationsPerEpoch, ...  
    ValidationPatience=6, ...                  
    ObjectiveMetric="accuracy", ...             
    OutputNetwork="best-validation", ...
    DispatchInBackground=false, ...
    Verbose=true, ...                 
    Plots="training-progress", ...              
    Metrics="accuracy");

[net, info] = trainnet(augTrain, dlnetwork(lgraph), "crossentropy", options);

save("mobilenetv2_trained.mat", "net", "info");

scoresVal = minibatchpredict(net, augVal);
classNames = categories(imdsVal.Labels);
trueLabels = imdsVal.Labels(:);

predLabels = scores2label(scoresVal, classNames);
predLabels = predLabels(:);

valAccuracy = mean(predLabels == trueLabels) * 100;
fprintf("\n--> Précision exacte MobileNetV2 sur la validation : %.2f %%\n", valAccuracy);

figure("Name", "Matrice de confusion MobileNetV2", "NumberTitle", "off");
confusionchart(trueLabels, predLabels, ...
    "RowSummary", "row-normalized", ...
    "ColumnSummary", "column-normalized");
title(sprintf("Matrice de Confusion - MobileNetV2 (Précision : %.2f %%)", valAccuracy));